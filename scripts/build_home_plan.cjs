const source = `/* Generated by scripts/build_home_plan.cjs. Units: mm; north is up. */
window.HOME_PLAN = (() => {
  const geometry = window.CAD_GEOMETRY;
  if (!geometry) throw new Error('CAD geometry must load before the home plan.');
  const photo = window.PHOTO_APPEARANCE;
  if (!photo?.overrides) throw new Error('Photo appearance must load before the home plan.');
  const appearance = photo.overrides;
  const metadata = ${JSON.stringify(metadata, null, 2)};
  return {
    ...geometry,
    ...appearance,
    cadSource: geometry.source,
    cadSourceAudit: geometry.geometryAudit,
    cadAssumptions: geometry.assumptions,
    appearanceAudit: photo.audit,
    appearanceAssumptions: photo.assumptions,
    rooms: (appearance.rooms || geometry.rooms).map(room => ({...room, at: (${JSON.stringify(labelPositions)})[room.id] || room.at})),
    ...metadata,
    assumptions: [...metadata.assumptions, ...photo.assumptions],
  };
})();
`;
fs.writeFileSync(path.join(root, 'home-plan.js'), source);
